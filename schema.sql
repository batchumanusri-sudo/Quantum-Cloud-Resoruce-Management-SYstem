CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50),
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'STUDENT'
        CHECK (ROLE IN ('ADMIN', 'RESEARCHER', 'STUDENT')),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE'
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PROVIDERS (
    PROVIDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVIDER_NAME VARCHAR2(100) NOT NULL,
    PROVIDER_TYPE VARCHAR2(50),
    REGION VARCHAR2(50),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE'
);

CREATE TABLE DEVICES (
    DEVICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEVICE_NAME VARCHAR2(100) NOT NULL,
    DEVICE_TYPE VARCHAR2(50),
    TOTAL_QUBITS NUMBER,
    AVAILABILITY VARCHAR2(20) DEFAULT 'AVAILABLE',
    PROVIDER_ID NUMBER,
    CONSTRAINT FK_DEVICE_PROVIDER
        FOREIGN KEY (PROVIDER_ID)
        REFERENCES PROVIDERS(PROVIDER_ID)
);

CREATE TABLE RESERVATIONS (
    RESERVATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DEVICE_ID NUMBER NOT NULL,
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,
    STATUS VARCHAR2(20) DEFAULT 'PENDING',
    CONSTRAINT FK_RES_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_RES_DEVICE
        FOREIGN KEY (DEVICE_ID) REFERENCES DEVICES(DEVICE_ID)
);

CREATE TABLE JOBS (
    JOB_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DEVICE_ID NUMBER NOT NULL,
    JOB_NAME VARCHAR2(100) NOT NULL,
    JOB_TYPE VARCHAR2(50),
    PRIORITY VARCHAR2(20) DEFAULT 'MEDIUM',
    STATUS VARCHAR2(20) DEFAULT 'PENDING',
    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_JOB_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_JOB_DEVICE
        FOREIGN KEY (DEVICE_ID) REFERENCES DEVICES(DEVICE_ID)
);

CREATE TABLE RESULTS (
    RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_ID NUMBER NOT NULL,
    EXECUTION_TIME NUMBER(10,2),
    RESULT_STATUS VARCHAR2(20),
    OUTPUT_DATA CLOB,
    COMPLETED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_RESULT_JOB
        FOREIGN KEY (JOB_ID) REFERENCES JOBS(JOB_ID)
);

CREATE TABLE FEEDBACK (
    FEEDBACK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    RATING NUMBER(1) CHECK (RATING BETWEEN 1 AND 5),
    COMMENTS VARCHAR2(1000),
    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_FEEDBACK_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);